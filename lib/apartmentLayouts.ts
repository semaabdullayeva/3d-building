// Vector apartment plans for the A1/B1/C1 blocks, traced from the architectural sheets.
// Coordinates are block plan metres (x east, y north) of the "A" unit; "B" units are its mirror (x → -x).

export type Rect = [number, number, number, number];
export type Side = "n" | "s" | "e" | "w";

export type FurnKind =
  | "bed" | "nightstand" | "wardrobe" | "sofa" | "armchair" | "coffee" | "dining" | "tv"
  | "desk" | "chair" | "counter" | "stove" | "sink" | "fridge" | "basin" | "wc" | "shower" | "roundtable";

export interface Furn { k: FurnKind; r: Rect; s?: Side }
/** Door leaf hinged at `h`, `w` long; `c` = closed direction, `o` = open direction (degrees, 0 = east, 90 = north). */
export interface Door { h: [number, number]; w: number; c: number; o: number }
export interface Room {
  no: number;
  name: string;
  area: number;
  r: Rect;
  at?: [number, number];
  fs?: number;
  /** Balconies/loggias: side carrying the railing. */
  rail?: Side;
}

export interface ApartmentLayout {
  total: number;
  rooms: Room[];
  /** Load-bearing / external walls (hatched). */
  walls: Rect[];
  /** Light partitions. */
  parts: Rect[];
  cols: Rect[];
  shafts: Rect[];
  shaftsX: Rect[];
  windows: Rect[];
  gaps: Rect[];
  doors: Door[];
  furn: Furn[];
  /** Unlabelled facade strips (planter / fin zones). */
  strips?: { r: Rect; rail: Side }[];
}

const f = (k: FurnKind, r: Rect, s?: Side): Furn => ({ k, r, s });
const d = (x: number, y: number, w: number, c: number, o: number): Door => ({ h: [x, y], w, c, o });

