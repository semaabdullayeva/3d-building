/** Vector plan for an A1/B1/C1 unit on the typical (3–14), 15th or 16th floor sheet; null elsewhere. */
export function apartmentLayout(planImage: string | undefined, type: string): LayoutMatch | null {
  if (!planImage) return null;
  const m = /^(A1|B1|C1)-floor-(\d+)\./.exec(planImage);
  if (!m) return null;
  const sheet = Number(m[2]);
  const mirror = type === "1D" || type.endsWith("B");
  let layout: ApartmentLayout | undefined;
  if (sheet <= 14) {
    layout = { "1A": L1A, "1B": L1A, "1C": L1C, "1D": L1C, "2A": L2A, "2B": L2A, "3A": L3A, "3B": L3A }[type];
  } else if (sheet === 15) {
    layout = { "3A": L3T, "3B": L3T, "4A": L4A, "4B": L4A }[type];
  } else if (sheet === 16) {
    layout = { "2A": L16_2A, "2B": L16_2A, "3A": L16_3A, "3B": L16_3A }[type];
  }
  return layout ? { layout, mirror } : null;
}
